/**
 * Compiles the authored eve agent packages under agent/ into a committed TypeScript
 * registry that the Next.js runtime can import.
 *
 * The eve packages are the source of truth. This script only mirrors them so the
 * persona text ships inside the serverless bundle without runtime filesystem reads.
 *
 *   bun run personas   # regenerate
 *   bun run test       # fails if the checked-in registry is stale
 */
import { readFileSync, readdirSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const subagentsDir = join(root, "agent", "subagents");
const OUT = join(root, "lib", "personas.generated.ts");

const DESCRIPTION_RE = /description:\s*\n?\s*"((?:[^"\\]|\\.)*)"/;
const MODEL_RE = /model:\s*([A-Z_]+|"[^"]+")/;
const MODEL_CONSTANT_RE = /export const ([A-Z_]+) = "([^"]+)"/g;

function read(path) {
  return readFileSync(path, "utf8");
}

export function buildRegistry() {
  const conduct = read(join(root, "agent", "lib", "boardroom-conduct.md")).trim();

  // Models are declared once in agent/lib/models.ts; each subagent names one of them.
  const modelSource = read(join(root, "agent", "lib", "models.ts"));
  const models = new Map(
    [...modelSource.matchAll(MODEL_CONSTANT_RE)].map(([, name, value]) => [name, value]),
  );

  const slugs = readdirSync(subagentsDir)
    .filter((name) => statSync(join(subagentsDir, name)).isDirectory())
    .sort();

  const packages = slugs.map((slug) => {
    const agentSource = read(join(subagentsDir, slug, "agent.ts"));
    const description = DESCRIPTION_RE.exec(agentSource)?.[1];
    const modelRef = MODEL_RE.exec(agentSource)?.[1];
    if (!description) throw new Error(`${slug}/agent.ts is missing a description`);
    if (!modelRef) throw new Error(`${slug}/agent.ts is missing a model`);
    const model = modelRef.startsWith('"') ? modelRef.slice(1, -1) : models.get(modelRef);
    if (!model) throw new Error(`${slug}/agent.ts names an unknown model ${modelRef}`);
    const instructions = read(join(subagentsDir, slug, "instructions.md")).trim();
    if (instructions.length < 200 && slug !== "secretary") {
      throw new Error(`${slug}/instructions.md is too thin to be a persona package`);
    }
    return { slug, description: description.replace(/\\"/g, '"'), model, instructions };
  });

  return { conduct, packages };
}

function render({ conduct, packages }) {
  const lines = [
    "// Generated by scripts/build-personas.mjs from the authored eve agent packages.",
    "// Source of truth: agent/subagents/<slug>/{agent.ts,instructions.md} and",
    "// agent/lib/boardroom-conduct.md. Do not edit by hand; run `bun run personas`.",
    "",
    "export type PersonaPackage = {",
    "  slug: string;",
    "  /** The eve subagent description, used to pick the right seat. */",
    "  description: string;",
    "  /** The AI Gateway model id declared in that subagent's agent.ts. */",
    "  model: string;",
    "  /** The subagent's own instructions.md, verbatim. */",
    "  instructions: string;",
    "};",
    "",
    `export const BOARDROOM_CONDUCT = ${JSON.stringify(conduct)};`,
    "",
    "export const PERSONA_PACKAGES: Record<string, PersonaPackage> = {",
  ];
  for (const p of packages) {
    lines.push(`  ${JSON.stringify(p.slug)}: {`);
    lines.push(`    slug: ${JSON.stringify(p.slug)},`);
    lines.push(`    description: ${JSON.stringify(p.description)},`);
    lines.push(`    model: ${JSON.stringify(p.model)},`);
    lines.push(`    instructions: ${JSON.stringify(p.instructions)},`);
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

export function renderRegistry() {
  return render(buildRegistry());
}

const invokedDirectly =
  process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (invokedDirectly) {
  const output = renderRegistry();
  writeFileSync(OUT, output, "utf8");
  const count = Object.keys(buildRegistry().packages).length;
  console.log(`Wrote lib/personas.generated.ts (${count} eve agent packages).`);
}

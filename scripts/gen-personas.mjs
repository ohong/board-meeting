// Bundles the persona packages under agent/subagents into a TypeScript module.
//
// Route handlers used to read these files with node:fs at request time. That works on a
// Node server but not on Cloudflare Workers, where process.cwd() is "/bundle" and the
// agent/ directory is not on the runtime filesystem at all — readdir throws and the board
// silently falls back to an empty catalog. Reading them at build time keeps one code path
// that works on every deployment target.
//
// Runs from the `prebuild`/`predev` scripts; regenerate by hand with `bun run gen:personas`.

import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = path.join(process.cwd(), "agent", "subagents");
const OUT = path.join(process.cwd(), "lib", "server", "personas.generated.ts");

const dirs = (await fs.readdir(ROOT, { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const packages = [];
const skipped = [];

for (const dir of dirs) {
  const base = path.join(ROOT, dir);
  let metaRaw, instructions;
  try {
    [metaRaw, instructions] = await Promise.all([
      fs.readFile(path.join(base, "persona.json"), "utf8"),
      fs.readFile(path.join(base, "instructions.md"), "utf8"),
    ]);
  } catch {
    skipped.push(`${dir}: missing persona.json or instructions.md`);
    continue;
  }
  let summary;
  try {
    summary = JSON.parse(metaRaw);
  } catch (error) {
    skipped.push(`${dir}: persona.json is not valid JSON (${error.message})`);
    continue;
  }
  // Same rules the runtime loader applied: an incomplete package is not selectable.
  if (summary.slug !== dir) {
    skipped.push(`${dir}: persona.json slug is "${summary.slug}"`);
    continue;
  }
  if (!instructions.trim()) {
    skipped.push(`${dir}: instructions.md is empty`);
    continue;
  }
  packages.push({ summary, instructions });
}

const body = `// GENERATED by scripts/gen-personas.mjs — do not edit.
// Source of truth: agent/subagents/<slug>/{persona.json,instructions.md}
// Regenerate with \`bun run gen:personas\` (also runs automatically before dev/build).

import type { PersonaSummary } from "@/lib/meeting/types";

export interface PersonaPackage {
  summary: PersonaSummary;
  instructions: string;
}

export const PERSONA_PACKAGES: PersonaPackage[] = ${JSON.stringify(packages, null, 2)};
`;

await fs.writeFile(OUT, body, "utf8");

console.log(`gen-personas: ${packages.length} package(s) -> lib/server/personas.generated.ts`);
for (const note of skipped) console.warn(`gen-personas: skipped ${note}`);
if (packages.length === 0) {
  console.error("gen-personas: no valid persona packages found");
  process.exit(1);
}
